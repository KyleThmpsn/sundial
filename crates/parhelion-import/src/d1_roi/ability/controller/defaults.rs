//! Native schema initialization for the retained Radiance controller and bank.
//! Shadowkeep 86657.20.08.23.1800.d2_rc___release, original 372770 clears the
//! instance before 372A60 applies its declaration default stream at +40.
//! The sparse words reproduce every byte of the independently decoded and original
//! 372470 replay outputs. Pair identities, interfaces and connected inputs still need
//! their own typed construction. These bytes alone are not a complete ability.

fn initialized(size: usize, absent: &[usize], words: &[(usize, u32)]) -> Vec<u8> {
    let mut bytes = vec![0; size];
    for &at in absent {
        bytes[at..at + 4].copy_from_slice(&u32::MAX.to_le_bytes());
    }
    for &(at, word) in words {
        bytes[at..at + 4].copy_from_slice(&word.to_le_bytes());
    }
    bytes
}

