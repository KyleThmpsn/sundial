/// The recovered name of one marker, when it has one.
#[must_use]
pub fn marker_name(hash: u32) -> Option<&'static str> {
    NAMES
        .binary_search_by_key(&hash, |(key, _)| *key)
        .ok()
        .map(|index| NAMES[index].1)
        .or_else(|| {
            PATH_NAMES
                .binary_search_by_key(&hash, |(key, _)| *key)
                .ok()
                .map(|index| PATH_NAMES[index].1)
        })
}
