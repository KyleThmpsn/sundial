/// The values stock perks set for one selector byte, most used first.
#[must_use]
pub fn observed(class: u32, offset: usize) -> &'static [(u8, u32, &'static str)] {
    OBSERVED
        .iter()
        .find(|(candidate, at, _)| *candidate == class && *at == offset)
        .map_or(&[], |(_, _, values)| *values)
}
