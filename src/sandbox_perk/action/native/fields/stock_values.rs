//! Every value the installed stock perks set for each native selector byte, with how many
//! of their actions set it and which named perks those are.
//!
//! A selector's meaning is not recovered from any string. What the game itself does with the
//! byte is recoverable, and it is the evidence a reader needs: when every perk that sets a
//! value is a grenade-payload perk, the value is about the fired projectile. Showing the
//! perks lets a reader judge that for themselves instead of trusting a label this project
//! invented. A count is evidence of use; the perk names are evidence of meaning.
//!
//! Generated by the scratch tool `taginfo/src/bin/selectors.rs` over the 1,800 stock perk
//! actions from the clean Shadowkeep packages. Regenerate it when the corpus changes.

